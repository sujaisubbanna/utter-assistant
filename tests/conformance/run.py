def check_policy(client: FramingClient, rep: Report) -> None:
    print("\n[policy: provenance + confirmation]")
    try:
        res = command_results(client, "run rm -rf /", "screen")
        results = res.get("results", []) if isinstance(res, dict) else []
        codes = [r.get("error", {}).get("code") for r in results]
        rep.check("screen-provenance terminal rejected -32006",
                  ERR_UNTRUSTED in codes, f"results={results}")
    except RpcError as exc:
        rep.check("screen-provenance terminal rejected -32006",
                  exc.code == ERR_UNTRUSTED, f"error={exc.code} {exc.message}")

    try:
        res = command_results(client, "run rm -rf /", "user")
        results = res.get("results", []) if isinstance(res, dict) else []
        codes = [r.get("error", {}).get("code") for r in results]
        rep.check("user-provenance terminal denied by policy -32003",
                  ERR_PERMISSION in codes, f"results={results}")
    except RpcError as exc:
        rep.check("user-provenance terminal denied by policy -32003",
                  exc.code == ERR_PERMISSION, f"error={exc.code} {exc.message}")

    confirmed: list[dict] = []

    def on_server_request(method, params, req_id):
        if method == "host.confirm":
            confirmed.append(params or {})
            return {"approved": True}
        raise RpcError(ERR_METHOD_NOT_FOUND, f"no handler for {method}")

    conf_client = FramingClient.connect_unix(runner_socket_path(), timeout=15.0,
                                             request_handler=on_server_request)
    try:
        res = conf_client.request("runner.command",
                                  {"utterance": "run echo hi", "provenance": "user"})
        results = res.get("results", []) if isinstance(res, dict) else []
        rep.check("confirmation path reachable (host.confirm or policy denial)",
                  bool(confirmed) or bool(results),
                  f"confirmed={len(confirmed)} results={results}")
    except RpcError as exc:
        rep.check("confirmation path reachable (host.confirm or policy denial)",
                  True, f"policy denied before confirm: {exc.code}")
    finally:
        conf_client.close()


