def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="utter M0/M1 conformance suite")
    ap.add_argument("--timeout", type=float, default=30.0)
    ap.add_argument("--keep", action="store_true", help="leave the runner running")
    args = ap.parse_args(argv)

    print("utter M0/M1 conformance suite")
    print(f"  repo:   {REPO}")
    print(f"  socket: {runner_socket_path()}")

    if not RUNNER_MAIN.exists():
        print("\nBLOCKED: runner/__main__.py is not present.")
        print(f"  expected: {RUNNER_MAIN}")
        return 2

    if not FAKE_RS.exists():
        print(f"\nBLOCKED: Rust fake not built: {FAKE_RS}")
        print("  run: cargo build --release --manifest-path plugins/fake_rs/Cargo.toml")
        return 2

    config = write_config()
    print(f"  config: {config}")

    runner = Runner(config=config, sock_path=runner_socket_path(),
                    log_dir=GENERATED, timeout=args.timeout)
    rep = Report(skip_label="NOT-YET-SUPPORTED: ")
    client = None
    try:
        runner.start()
        if not runner.wait_ready():
            print("\nBLOCKED: runner did not become ready.")
            print("--- runner log tail ---")
            print(runner.tail_log())
            return 2
        client = runner.connect()
        # M0
        check_handshake(client, rep)
        check_vertical_slice(client, rep)
        check_policy(client, rep)
        check_cross_language(client, rep)
        # M1
        check_backpressure_e2e(client, rep)
        check_reliable_flow(client, rep)
        check_runner_invoke(client, rep)
        check_validate_plugin(client, rep)
        check_handles_fd(client, rep)
        check_memfd_ring(client, rep)
    except (FramingTimeout, TransportClosed, OSError) as exc:
        print(f"\nBLOCKED: transport error: {exc}")
        print("--- runner log tail ---")
        print(runner.tail_log())
        return 2
    finally:
        if client is not None:
            client.close()
        if not args.keep:
            runner.stop()

    # Socket default-deny needs its own runner instances; run after the main one.
    check_socket_default_deny(rep)

    summary = rep.summary()
    print(f"\n=== {summary['passed']}/{summary['total']} checks passed, "
          f"{summary['skipped']} not-yet-supported ===")
    if rep.failed:
        print("FAILED:")
        for c in rep.failed:
            print(f"  - {c['name']}: {c['detail']}")
        return 1
    if rep.skips:
        print("NOT-YET-SUPPORTED (runner M1 features pending):")
        for s in rep.skips:
            print(f"  - {s['name']}: {s['reason']}")
    print("ALL ASSERTIONS PASSED")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
