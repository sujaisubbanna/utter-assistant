def check_handshake(client: FramingClient, rep: Report) -> None:
    print("\n[handshake / negotiation]")
    status = client.request("runner.status", {})
    plugins = plugins_by_id(status)
    rep.check("runner.status returns plugins", bool(plugins),
              f"ids={sorted(plugins)}")

    py = find_plugin(status, "fake_py")
    rs = find_plugin(status, "fake_rs")
    rep.check("fake_py handshaken", py is not None)
    rep.check("fake_rs handshaken (cross-language)", rs is not None)

    if py:
        rep.check("fake_py status ok", py.get("status") in ("ok", "degraded"),
                  f"status={py.get('status')}")
        rep.check("fake_py has epoch", py.get("epoch") is not None,
                  f"epoch={py.get('epoch')}")
        provides = set(py.get("provides", []) or [])
        requires = set(py.get("requires", []) or [])
        rep.check("fake_py provides∩requires non-empty",
                  bool(provides & requires),
                  f"intersection={sorted(provides & requires)}")
        rep.check("fake_py provides router/action caps",
                  any(c.startswith("action.") for c in provides),
                  f"provides={sorted(provides)}")

    rep.check("unknown-capability tolerated (handshake succeeded)", py is not None,
              "experimental/* caps accepted without error")

    # A missing require is an error (fail closed). Asserted against the runner's
    # own validator via a subprocess probe so we do not import runner code.
    probe = subprocess.run(
        [sys.executable, "-c", (
            "import sys; sys.path.insert(0, '.');"
            "from runner.plugin import validate_capabilities;"
            "from runner.rpc import RpcError;"
            "\ntry:\n"
            "    validate_capabilities(['action.open_url@1'], ['does.not.exist@1'])\n"
            "    print('NO_ERROR')\n"
            "except RpcError as e:\n"
            "    print('ERROR', e.code)\n"
        )],
        cwd=str(REPO), capture_output=True, text=True, timeout=15,
    )
    out = (probe.stdout or "").strip()
    rep.check("missing-require rejected (fail closed)",
              out.startswith("ERROR"),
              f"validator said: {out or probe.stderr.strip()[:120]}")


