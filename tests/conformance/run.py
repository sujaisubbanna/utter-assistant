def write_config() -> Path:
    GENERATED.mkdir(parents=True, exist_ok=True)
    CONFIG_PATH.write_text(runner_config(
        comment="GENERATED by tests/conformance/run.py — do not edit.",
        socket="# Dev override: the conformance client is a same-uid python process. The\n"
               "# default-deny tests below use dedicated configs with allow_binaries/token.\n"
               "allow_same_uid = true",
        confirm_timeout_ms=5000,
        policy='# terminal stays off by default; the suite asserts the disabled path.\n'
               'disabled_ops = ["terminal"]',
    ), encoding="utf-8")
    return CONFIG_PATH


def write_deny_config() -> Path:
    """Default-deny: allow_binaries lists a binary that is NOT our client."""
    GENERATED.mkdir(parents=True, exist_ok=True)
    DENY_CONFIG_PATH.write_text(runner_config(
        comment="GENERATED by tests/conformance/run.py — default-deny probe.",
        socket="# Only this (nonexistent) binary may connect; our python client must be denied.\n"
               'allow_binaries = ["definitely-not-our-client"]',
    ), encoding="utf-8")
    return DENY_CONFIG_PATH


def write_allow_config() -> Path:
    """Allow-list the python interpreter basename so our client is accepted.

    The runner verifies ``/proc/<pid>/exe``, which resolves symlinks, so we must
    list the *real* interpreter basename (e.g. ``python3.14``), not ``python``.
    """
    GENERATED.mkdir(parents=True, exist_ok=True)
    py_name = Path(os.path.realpath(sys.executable)).name
    ALLOW_CONFIG_PATH.write_text(runner_config(
        comment="GENERATED by tests/conformance/run.py — allow-list probe.",
        socket=f'allow_binaries = ["{py_name}"]',
    ), encoding="utf-8")
    return ALLOW_CONFIG_PATH


def write_token_config() -> Path:
    """Token auth: same-uid client must call runner.auth with the token."""
    GENERATED.mkdir(parents=True, exist_ok=True)
    TOKEN_CONFIG_PATH.write_text(runner_config(
        comment="GENERATED by tests/conformance/run.py — token-auth probe.",
        socket=f'token = "{TOKEN}"',
    ), encoding="utf-8")
    return TOKEN_CONFIG_PATH


