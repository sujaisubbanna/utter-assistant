#!/usr/bin/env python3
"""M0/M1 conformance suite for the utter plugin protocol.

Starts the runner (``python -m runner --config <generated>``) with a config that
loads the Python and Rust fake plugins, then asserts the frozen handshake,
negotiation, the vertical slice, runner-enforced policy, cross-language
handshaking, and the M1 client API (streams, flow control, ``runner.invoke``,
``runner.validate_plugin``, handles/fd.pass, socket default-deny).

The client framing is implemented independently in ``framing_client.py`` — this
suite never imports the runner's framing code.

M1 features that the runner has not implemented yet are reported as
``NOT-YET-SUPPORTED`` (counted separately, never as failures), so the suite can
run against an M0 runner while the M1 lane lands.

Usage::

    .venv-agent/bin/python tests/conformance/run.py [--keep] [--timeout 30]

Exit code 0 = all assertions passed (or only not-yet-supported skips). If the
runner is absent the suite reports exactly which step blocked and exits 2.
"""
