def check_handles_fd(client: FramingClient, rep: Report) -> None:
    """(5) Handles + fd.pass through the runner.

    The runner's handle store is populated internally; there is no client-facing
    ``handle.create`` yet, so the full inline-fetch / fd.pass round trip cannot
    be seeded from the conformance client. We assert the endpoints exist and
    behave correctly for unknown handles, and exercise the SCM_RIGHTS mechanism
    independently over a socketpair.
    """
    print("\n[M1.5 handles + fd.pass through the runner]")

    # Probe handle.fetch with a synthetic (unknown) handle: the endpoint must
    # exist and reject it as a handle error, not method-not-found.
    synthetic = "handle://" + hashlib.sha256(b"conformance").hexdigest()
    try:
        client.handle_fetch(synthetic, timeout=10.0)
        rep.check("handle.fetch endpoint exists", False,
                  "unknown handle unexpectedly fetched")
    except RpcError as exc:
        if _is_not_implemented(exc):
            rep.skip("handle.fetch endpoint", f"runner has no handle.fetch ({exc.code})")
        else:
            rep.check("handle.fetch endpoint exists (unknown handle rejected)",
                      exc.code in (-32000, -32602, -32003),
                      f"error={exc.code} {exc.message}")
    except (FramingTimeout, TransportClosed) as exc:
        rep.skip("handle.fetch endpoint", f"timed out: {exc}")

    # handle.stat endpoint.
    try:
        client.request("handle.stat", {"handle": synthetic}, timeout=10.0)
        rep.check("handle.stat endpoint exists", False, "unknown handle statted")
    except RpcError as exc:
        if _is_not_implemented(exc):
            rep.skip("handle.stat endpoint", f"runner has no handle.stat ({exc.code})")
        else:
            rep.check("handle.stat endpoint exists (unknown handle rejected)",
                      exc.code in (-32000, -32602, -32003),
                      f"error={exc.code} {exc.message}")
    except (FramingTimeout, TransportClosed) as exc:
        rep.skip("handle.stat endpoint", f"timed out: {exc}")

    # fd.pass endpoint: kind=handle with an unknown handle must be rejected.
    try:
        client.fd_pass("handle", {"handle": synthetic}, timeout=10.0)
        rep.check("fd.pass endpoint exists", False, "unknown handle passed")
    except RpcError as exc:
        if _is_not_implemented(exc):
            rep.skip("fd.pass endpoint", f"runner has no fd.pass ({exc.code})")
        else:
            rep.check("fd.pass endpoint exists (unknown handle rejected)",
                      exc.code in (-32000, -32602, -32003),
                      f"error={exc.code} {exc.message}")
    except (FramingTimeout, TransportClosed) as exc:
        rep.skip("fd.pass endpoint", f"timed out: {exc}")

    # SCM_RIGHTS mechanism: independent socketpair round trip (proves the
    # client-side fd.pass/recv_fds implementation is correct).
    try:
        a, b = FramingClient.socketpair(timeout=5.0)
        try:
            fd = os.memfd_create("conformance-fd", 0)
            os.write(fd, b"scm-rights-payload")
            os.lseek(fd, 0, 0)
            a.send_fd_frame("memfd", {"data": "scm-rights-payload"}, fds=[fd])
            os.close(fd)
            _data, fds = b.recv_fds(timeout=3.0)
            ok = bool(fds) and os.read(fds[0], 64) == b"scm-rights-payload"
            for f in fds:
                os.close(f)
            rep.check("SCM_RIGHTS fd round trip (socketpair)", ok, f"fds={len(fds)}")
        finally:
            a.close()
            b.close()
    except (OSError, FramingError) as exc:
        rep.skip("SCM_RIGHTS fd round trip", f"not supported: {exc}")

    # -- end-to-end: handle.create → handle.fetch inline -------------------- #
    payload = b"utter inline handle \x00\x01\x02"
    created = None
    try:
        created = client.request(
            "handle.create",
            {"data_b64": base64.b64encode(payload).decode("ascii")},
            timeout=10.0,
        )
        rep.check("handle.create returns handle/sha256/size",
                  bool(created.get("handle")) and created.get("size") == len(payload),
                  f"result={created}")
    except RpcError as exc:
        if _is_not_implemented(exc):
            rep.skip("handle.create", f"runner has no handle.create ({exc.code})")
        else:
            rep.check("handle.create returns handle/sha256/size", False,
                      f"error {exc.code}: {exc.message}")
    except (FramingTimeout, TransportClosed) as exc:
        rep.skip("handle.create", f"timed out: {exc}")

    if created and created.get("handle"):
        try:
            fetched = client.handle_fetch(created["handle"], timeout=10.0)
            data = base64.b64decode(fetched.get("data_b64", ""))
            digest = hashlib.sha256(data).hexdigest()
            rep.check("handle.fetch inline sha256 matches created content",
                      digest == created.get("sha256") == hashlib.sha256(payload).hexdigest(),
                      f"sha256={digest}")
            rep.check("handle.fetch inline size correct",
                      fetched.get("size") == len(payload),
                      f"size={fetched.get('size')} expected={len(payload)}")
        except RpcError as exc:
            rep.check("handle.fetch inline sha256 matches created content", False,
                      f"error {exc.code}: {exc.message}")
        except (FramingTimeout, TransportClosed) as exc:
            rep.skip("handle.fetch inline", f"timed out: {exc}")

    # -- end-to-end: >64 KiB handle → -32007 -------------------------------- #
    try:
        big = client.request("handle.create", {"size": 128 * 1024}, timeout=10.0)
        big_handle = big.get("handle")
        rep.check("handle.create large (128 KiB)", bool(big_handle),
                  f"size={big.get('size')}")
        if big_handle:
            try:
                client.handle_fetch(big_handle, timeout=10.0)
                rep.check("handle.fetch >64KiB rejected -32007", False,
                          "fetch unexpectedly succeeded")
            except RpcError as exc:
                rep.check("handle.fetch >64KiB rejected -32007",
                          exc.code == ERR_HANDLE_TOO_LARGE,
                          f"error={exc.code} {exc.message}")
    except RpcError as exc:
        if _is_not_implemented(exc):
            rep.skip("handle.fetch >64KiB rejected -32007",
                     f"runner has no handle.create ({exc.code})")
        else:
            rep.check("handle.fetch >64KiB rejected -32007", False,
                      f"error {exc.code}: {exc.message}")
    except (FramingTimeout, TransportClosed) as exc:
        rep.skip("handle.fetch >64KiB rejected -32007", f"timed out: {exc}")

    # -- end-to-end: fd.pass kind="handle" over the socket transport -------- #
    if created and created.get("handle"):
        try:
            result, fds = client.fd_pass_recv("handle", {"handle": created["handle"]},
                                              timeout=10.0)
            rep.check("fd.pass kind=handle returns {}", result == {}, f"result={result}")
            rep.check("fd.pass kind=handle delivers exactly one fd", len(fds) == 1,
                      f"fds={len(fds)}")
            if fds:
                content = os.read(fds[0], 4096)
                rep.check("fd.pass kind=handle content matches",
                          content == payload, f"content={content!r}")
                for f in fds:
                    os.close(f)
        except RpcError as exc:
            if _is_not_implemented(exc):
                rep.skip("fd.pass kind=handle", f"runner has no fd.pass ({exc.code})")
            else:
                rep.check("fd.pass kind=handle returns {}", False,
                          f"error {exc.code}: {exc.message}")
        except (FramingTimeout, TransportClosed, OSError) as exc:
            rep.skip("fd.pass kind=handle", f"not supported: {exc}")

    # -- end-to-end: fd.pass kind="memfd" (plain memfd, not a true ring) ---- #
    try:
        result, fds = client.fd_pass_recv("memfd", {"data": "memfd-payload", "size": 4096},
                                          timeout=10.0)
        # kind=handle returns {}; kind=memfd returns its geometry metadata.
        rep.check("fd.pass kind=memfd returns metadata",
                  isinstance(result, dict) and result.get("kind") == "memfd",
                  f"result={result}")
        rep.check("fd.pass kind=memfd delivers exactly one fd", len(fds) == 1,
                  f"fds={len(fds)}")
        if fds:
            content = os.read(fds[0], 64)
            rep.check("fd.pass kind=memfd content matches",
                      content.startswith(b"memfd-payload"), f"content={content[:32]!r}")
            for f in fds:
                os.close(f)
    except RpcError as exc:
        if _is_not_implemented(exc):
            rep.skip("fd.pass kind=memfd", f"runner has no fd.pass memfd ({exc.code})")
        else:
            rep.check("fd.pass kind=memfd returns metadata", False,
                      f"error {exc.code}: {exc.message}")
    except (FramingTimeout, TransportClosed, OSError) as exc:
        rep.skip("fd.pass kind=memfd", f"not supported: {exc}")

    # memfd.ring is a plain memfd in the runner (not a true ring buffer), so
    # ring semantics (wrap-around / read-write cursors) are not testable yet.
    rep.skip("memfd.ring wrap-around semantics",
             "runner memfd.ring is a plain memfd, not a true ring buffer")


def check_socket_default_deny(rep: Report) -> None:
    """(6) Socket default-deny: unlisted client rejected, allow-listed accepted."""
    print("\n[M1.6 socket default-deny]")
    deny_sock = str(GENERATED / "runner-deny.sock")
    allow_sock = str(GENERATED / "runner-allow.sock")

    # Default-deny: allow_binaries lists a binary that is not our client.
    deny = Runner(timeout=20.0, config=write_deny_config(), log_dir=GENERATED,
                  sock_path=deny_sock, log_name="runner-deny.log")
    try:
        deny.start()
        if not deny.wait_ready():
            rep.skip("socket default-deny", "deny-config runner did not start")
        else:
            try:
                c = FramingClient.connect_unix(deny_sock, timeout=5.0)
                try:
                    c.request("runner.status", {}, timeout=3.0)
                    rep.check("unlisted client rejected", False,
                              "connection was accepted and served")
                except (TransportClosed, FramingTimeout, OSError):
                    rep.check("unlisted client rejected", True,
                              "connection closed / no response")
                finally:
                    c.close()
            except OSError as exc:
                rep.check("unlisted client rejected", True, f"connect refused: {exc}")
    finally:
        deny.stop()

    # Allow-list: our interpreter basename is permitted.
    allow = Runner(timeout=20.0, config=write_allow_config(), log_dir=GENERATED,
                   sock_path=allow_sock, log_name="runner-allow.log")
    try:
        allow.start()
        if not allow.wait_ready():
            rep.skip("socket allow-list accepted", "allow-config runner did not start")
        else:
            try:
                c = FramingClient.connect_unix(allow_sock, timeout=5.0)
                try:
                    status = c.request("runner.status", {}, timeout=5.0)
                    rep.check("allow-listed client accepted",
                              bool(status.get("plugins")), f"plugins={len(status.get('plugins', []))}")
                finally:
                    c.close()
            except (RpcError, TransportClosed, FramingTimeout, OSError) as exc:
                rep.check("allow-listed client accepted", False, str(exc))
    finally:
        allow.stop()

    # Token auth: same-uid client must call runner.auth before other methods.
    token_sock = str(GENERATED / "runner-token.sock")
    tok = Runner(timeout=20.0, config=write_token_config(), log_dir=GENERATED,
                 sock_path=token_sock, log_name="runner-token.log")
    try:
        tok.start()
        if not tok.wait_ready():
            rep.skip("socket token auth", "token-config runner did not start")
        else:
            try:
                c = FramingClient.connect_unix(token_sock, timeout=5.0)
                try:
                    # Unauthenticated call must be denied.
                    try:
                        c.request("runner.status", {}, timeout=3.0)
                        rep.check("token: unauthenticated call denied", False,
                                  "call succeeded without auth")
                    except RpcError as exc:
                        rep.check("token: unauthenticated call denied",
                                  exc.code == ERR_PERMISSION,
                                  f"error={exc.code} {exc.message}")
                    # Authenticate, then the call must succeed.
                    c.auth(TOKEN, timeout=3.0)
                    status = c.request("runner.status", {}, timeout=5.0)
                    rep.check("token: authenticated call accepted",
                              bool(status.get("plugins")),
                              f"plugins={len(status.get('plugins', []))}")
                finally:
                    c.close()
            except (RpcError, TransportClosed, FramingTimeout, OSError) as exc:
                rep.check("token: authenticated call accepted", False, str(exc))
    finally:
        tok.stop()


def check_memfd_ring(client: FramingClient, rep: Report) -> None:
    """(7) Memfd ring buffer round trip (if implemented)."""
    print("\n[M1.7 memfd ring buffer]")
    try:
        res = client.invoke("fake_py", "memfd.ring", {"size": 4096}, timeout=10.0)
        if isinstance(res, dict) and res.get("ok"):
            rep.check("memfd ring created", res.get("size") == 4096, f"result={res}")
            # Exercise a real fd round trip over a socketpair (independent of the
            # runner): send a memfd and read it back.
            a, b = FramingClient.socketpair(timeout=5.0)
            try:
                fd = os.memfd_create("ring-test", 0)
                os.ftruncate(fd, 4096)
                os.write(fd, b"ring-data")
                os.lseek(fd, 0, 0)
                a.send_fd_frame("memfd.ring", {"size": 4096}, fds=[fd])
                os.close(fd)
                data, fds = b.recv_fds(timeout=3.0)
                ok = bool(fds) and os.read(fds[0], 64).startswith(b"ring-data")
                for f in fds:
                    os.close(f)
                rep.check("memfd fd round trip (SCM_RIGHTS)", ok,
                          f"fds={len(fds)}")
            finally:
                a.close()
                b.close()
        else:
            rep.skip("memfd ring", f"fake reports not supported: {res}")
    except RpcError as exc:
        if _is_not_implemented(exc):
            rep.skip("memfd ring", f"runner has no runner.invoke ({exc.code})")
        else:
            rep.check("memfd ring created", False, f"error {exc.code}: {exc.message}")
    except (FramingTimeout, TransportClosed, OSError) as exc:
        rep.skip("memfd ring", f"not supported: {exc}")


