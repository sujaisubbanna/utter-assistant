def plugins_by_id(status: dict) -> dict:
    out = {}
    for p in status.get("plugins", []) or []:
        pid = p.get("id") or p.get("name")
        if pid:
            out[pid] = p
    return out


def find_plugin(status: dict, needle: str) -> dict | None:
    for pid, p in plugins_by_id(status).items():
        if needle in str(pid) or needle in str(p.get("name", "")):
            return p
    return None


def command_results(client: FramingClient, utterance: str, provenance: str = "user") -> dict:
    return client.request("runner.command",
                          {"utterance": utterance, "provenance": provenance})


def _is_not_implemented(exc: RpcError) -> bool:
    return exc.code == ERR_METHOD_NOT_FOUND


