def check_backpressure_e2e(client: FramingClient, rep: Report) -> None:
    """(1) End-to-end lossy backpressure through the runner."""
    print("\n[M1.1 end-to-end backpressure through the runner]")
    try:
        sub = client.subscribe("fake.frames", {"rate": "max"}, mode="lossy", timeout=5.0)
    except RpcError as exc:
        if _is_not_implemented(exc):
            rep.skip("e2e lossy backpressure", f"runner has no stream.subscribe ({exc.code})")
            return
        rep.check("e2e lossy backpressure", False, f"error {exc.code}: {exc.message}")
        return
    except (FramingTimeout, TransportClosed) as exc:
        rep.skip("e2e lossy backpressure", f"stream.subscribe timed out: {exc}")
        return

    stream_id = str(sub.get("stream_id") or "")
    rep.check("stream.subscribe returns stream_id", bool(stream_id), f"sub={sub}")
    rep.check("stream.subscribe reports mode", sub.get("mode") in ("lossy", None),
              f"mode={sub.get('mode')}")

    # Deliberately slow consumer with a bounded read budget (drop-oldest).
    seqs: list[int] = []
    responsive = 0
    t_end = time.monotonic() + 1.5
    while time.monotonic() < t_end:
        time.sleep(0.05)
        notes = client.drain_notifications(timeout=0.01)
        batch = [int((n.get("params") or {}).get("seq") or 0)
                 for n in notes
                 if (n.get("params") or {}).get("stream_id") == stream_id
                 and "seq" in (n.get("params") or {})]
        if len(batch) > 4:
            batch = batch[-4:]  # drop-oldest
        seqs.extend(batch)
        t0 = time.perf_counter()
        try:
            client.request("runner.status", {}, timeout=2.0)
            if (time.perf_counter() - t0) < 1.0:
                responsive += 1
        except (RpcError, FramingTimeout, TransportClosed):
            pass

    gaps = sum(1 for a, b in zip(seqs, seqs[1:]) if b > a + 1)
    rep.check("(a) other RPCs stay responsive while streaming", responsive > 0,
              f"status_calls={responsive}")
    rep.check("(b) drop-oldest with seq gaps", gaps > 0,
              f"frames={len(seqs)} gaps={gaps}")

    # (c) stream.stop idempotent
    try:
        client.stop_stream(stream_id, timeout=5.0)
        client.stop_stream(stream_id, timeout=5.0)  # second call must not raise
        rep.check("(c) stream.stop idempotent", True, "two stops accepted")
    except RpcError as exc:
        rep.check("(c) stream.stop idempotent", False, f"error {exc.code}: {exc.message}")
    except (FramingTimeout, TransportClosed) as exc:
        rep.check("(c) stream.stop idempotent", False, str(exc))


def check_reliable_flow(client: FramingClient, rep: Report) -> None:
    """(2) Reliable flow control: pause on credit exhaustion, resume on ack."""
    print("\n[M1.2 reliable flow control]")
    try:
        sub = client.subscribe("fake.frames", {}, mode="reliable", timeout=5.0)
    except RpcError as exc:
        if _is_not_implemented(exc):
            rep.skip("reliable flow control", f"runner has no stream.subscribe ({exc.code})")
            return
        rep.check("reliable flow control", False, f"error {exc.code}: {exc.message}")
        return
    except (FramingTimeout, TransportClosed) as exc:
        rep.skip("reliable flow control", f"stream.subscribe timed out: {exc}")
        return

    stream_id = str(sub.get("stream_id") or "")
    rep.check("reliable subscribe reports mode", sub.get("mode") in ("reliable", None),
              f"mode={sub.get('mode')}")

    # Consume without acking: the server should pause at the credit window.
    first = client.collect_stream(stream_id, duration=0.6)
    first_seqs = [int((n.get("params") or {}).get("seq") or 0) for n in first]
    max_before = max(first_seqs) if first_seqs else 0
    rep.check("reliable stream delivers frames", max_before > 0,
              f"frames={len(first_seqs)} max_seq={max_before}")

    # No acks -> the producer must pause (seq stops advancing).
    time.sleep(0.4)
    paused = client.collect_stream(stream_id, duration=0.3)
    paused_seqs = [int((n.get("params") or {}).get("seq") or 0) for n in paused]
    max_paused = max(paused_seqs) if paused_seqs else max_before
    rep.check("server pauses when credits exhausted", max_paused <= max_before + 2,
              f"max_before={max_before} max_after_pause={max_paused}")

    # Ack the highest seq -> credit replenished -> stream resumes.
    try:
        client.ack(stream_id, max_paused, timeout=5.0)
    except RpcError as exc:
        if _is_not_implemented(exc):
            rep.skip("reliable resume after ack", f"runner has no stream.ack ({exc.code})")
            client.stop_stream(stream_id)
            return
        rep.check("reliable resume after ack", False, f"ack error {exc.code}: {exc.message}")
        client.stop_stream(stream_id)
        return
    resumed = client.collect_stream(stream_id, duration=0.5)
    resumed_seqs = [int((n.get("params") or {}).get("seq") or 0) for n in resumed]
    max_resumed = max(resumed_seqs) if resumed_seqs else max_paused
    rep.check("stream resumes after stream.ack", max_resumed > max_paused,
              f"max_paused={max_paused} max_resumed={max_resumed}")
    client.stop_stream(stream_id)


