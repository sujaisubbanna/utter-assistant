def measure_handles_fd(client: FramingClient) -> dict:
    """Handles + fd.pass through the runner (end-to-end + SCM_RIGHTS mechanism)."""
    print("\n[M1.5 handles + fd.pass through the runner]")
    result: dict = {}
    synthetic = "handle://" + hashlib.sha256(b"spike").hexdigest()

    # Endpoint probes with an unknown handle.
    for label, fn in (
        ("handle.fetch", lambda: client.handle_fetch(synthetic, timeout=10.0)),
        ("handle.stat", lambda: client.request("handle.stat", {"handle": synthetic}, timeout=10.0)),
        ("fd.pass", lambda: client.fd_pass("handle", {"handle": synthetic}, timeout=10.0)),
    ):
        try:
            fn()
            result[label] = {"endpoint": True, "unknown_handle_rejected": False}
        except RpcError as exc:
            result[label] = {"endpoint": exc.code != -32601,
                             "unknown_handle_rejected": exc.code in (-32000, -32602, -32003),
                             "code": exc.code}
        except (FramingTimeout, TransportClosed) as exc:
            result[label] = {"endpoint": False, "reason": str(exc)}

    # End-to-end: create → fetch inline (hash match).
    payload = b"utter spike handle \x00\x01\x02"
    handle = None
    try:
        created = client.request(
            "handle.create",
            {"data_b64": base64.b64encode(payload).decode("ascii")},
            timeout=10.0,
        )
        handle = created.get("handle")
        result["create"] = {"handle": handle, "size": created.get("size")}
        fetched = client.handle_fetch(handle, timeout=10.0)
        data = base64.b64decode(fetched.get("data_b64", ""))
        result["fetch_inline"] = {
            "sha256_match": hashlib.sha256(data).hexdigest() == created.get("sha256"),
            "size": fetched.get("size"),
        }
    except RpcError as exc:
        result["create"] = {"error": exc.code, "message": exc.message}
    except (FramingTimeout, TransportClosed) as exc:
        result["create"] = {"error": str(exc)}

    # End-to-end: >64 KiB → -32007.
    try:
        big = client.request("handle.create", {"size": 128 * 1024}, timeout=10.0)
        try:
            client.handle_fetch(big["handle"], timeout=10.0)
            result["fetch_too_large"] = {"rejected": False}
        except RpcError as exc:
            result["fetch_too_large"] = {"rejected": exc.code == -32007, "code": exc.code}
    except (RpcError, FramingTimeout, TransportClosed) as exc:
        result["fetch_too_large"] = {"error": str(exc)}

    # End-to-end: fd.pass kind=handle over the socket transport.
    if handle:
        try:
            res, fds = client.fd_pass_recv("handle", {"handle": handle}, timeout=10.0)
            content = os.read(fds[0], 4096) if fds else b""
            result["fd_pass_handle"] = {
                "result": res,
                "fds": len(fds),
                "content_match": content == payload,
            }
            for f in fds:
                os.close(f)
        except (RpcError, FramingTimeout, TransportClosed, OSError) as exc:
            result["fd_pass_handle"] = {"error": str(exc)}

    # End-to-end: fd.pass kind=memfd.
    try:
        res, fds = client.fd_pass_recv("memfd", {"data": "memfd-payload", "size": 4096},
                                       timeout=10.0)
        content = os.read(fds[0], 64) if fds else b""
        result["fd_pass_memfd"] = {
            "result": res,
            "fds": len(fds),
            "content_match": content.startswith(b"memfd-payload"),
        }
        for f in fds:
            os.close(f)
    except (RpcError, FramingTimeout, TransportClosed, OSError) as exc:
        result["fd_pass_memfd"] = {"error": str(exc)}

    # SCM_RIGHTS mechanism over a socketpair (independent of the runner).
    try:
        a, b = FramingClient.socketpair(timeout=5.0)
        try:
            fd = os.memfd_create("spike-fd", 0)
            os.write(fd, b"scm-rights-payload")
            os.lseek(fd, 0, 0)
            a.send_fd_frame("memfd", {"data": "scm-rights-payload"}, fds=[fd])
            os.close(fd)
            _data, fds = b.recv_fds(timeout=3.0)
            ok = bool(fds) and os.read(fds[0], 64) == b"scm-rights-payload"
            for f in fds:
                os.close(f)
            result["scm_rights_round_trip"] = ok
        finally:
            a.close()
            b.close()
    except (OSError, Exception) as exc:  # noqa: BLE001
        result["scm_rights_round_trip"] = False
        result["scm_rights_error"] = str(exc)

    result["ring_semantics"] = "not-yet-supported: runner memfd.ring is a plain memfd"
    fi = result.get("fetch_inline", {})
    fh = result.get("fd_pass_handle", {})
    print(f"    create={result.get('create')} fetch_inline={fi} "
          f"too_large={result.get('fetch_too_large')}")
    print(f"    fd_pass_handle={fh} fd_pass_memfd={result.get('fd_pass_memfd')} "
          f"scm_rights={result.get('scm_rights_round_trip')}")
    return result


def measure_default_deny() -> dict:
    """Socket default-deny: unlisted rejected, allow-listed accepted."""
    print("\n[M1.6 socket default-deny]")
    result: dict = {}
    deny_sock = str(GENERATED / "spike-deny.sock")
    allow_sock = str(GENERATED / "spike-allow.sock")

    # deny config
    deny_cfg = GENERATED / "spike_deny.toml"
    deny_cfg.write_text(runner_config(
        comment="GENERATED by scripts/m0_spike.py — default-deny probe.",
        socket='allow_binaries = ["definitely-not-our-client"]',
    ), encoding="utf-8")
    deny = Runner(timeout=20.0, config=deny_cfg, sock_path=deny_sock,
                  log_dir=GENERATED, log_name="spike-deny.log", tail_lines=30)
    try:
        deny.start()
        if deny.wait_ready():
            try:
                c = FramingClient.connect_unix(deny_sock, timeout=5.0)
                try:
                    c.request("runner.status", {}, timeout=3.0)
                    result["unlisted_rejected"] = False
                except (TransportClosed, FramingTimeout, OSError):
                    result["unlisted_rejected"] = True
                finally:
                    c.close()
            except OSError:
                result["unlisted_rejected"] = True
        else:
            result["unlisted_rejected"] = None
    finally:
        deny.stop()

    # allow config (realpath basename)
    allow_cfg = GENERATED / "spike_allow.toml"
    py_name = Path(os.path.realpath(sys.executable)).name
    allow_cfg.write_text(runner_config(
        comment="GENERATED by scripts/m0_spike.py — allow-list probe.",
        socket=f'allow_binaries = ["{py_name}"]',
    ), encoding="utf-8")
    allow = Runner(timeout=20.0, config=allow_cfg, sock_path=allow_sock,
                   log_dir=GENERATED, log_name="spike-allow.log", tail_lines=30)
    try:
        allow.start()
        if allow.wait_ready():
            try:
                c = FramingClient.connect_unix(allow_sock, timeout=5.0)
                try:
                    status = c.request("runner.status", {}, timeout=5.0)
                    result["allow_listed_accepted"] = bool(status.get("plugins"))
                finally:
                    c.close()
            except (RpcError, TransportClosed, FramingTimeout, OSError) as exc:
                result["allow_listed_accepted"] = False
                result["allow_error"] = str(exc)
        else:
            result["allow_listed_accepted"] = None
    finally:
        allow.stop()

    print(f"    unlisted_rejected={result.get('unlisted_rejected')} "
          f"allow_listed_accepted={result.get('allow_listed_accepted')}")
    return result


