def measure_latency(client: FramingClient, n: int) -> dict:
    print(f"\n[1] RPC round-trip latency (N={n} runner.status)")
    samples: list[float] = []
    for _ in range(n):
        t0 = time.perf_counter()
        client.request("runner.status", {})
        samples.append((time.perf_counter() - t0) * 1000.0)
    samples.sort()

    def pct(p: float) -> float:
        idx = min(len(samples) - 1, int(round(p / 100.0 * (len(samples) - 1))))
        return samples[idx]

    out = {
        "n": n,
        "p50_ms": round(pct(50), 3),
        "p95_ms": round(pct(95), 3),
        "p99_ms": round(pct(99), 3),
        "max_ms": round(samples[-1], 3),
        "min_ms": round(samples[0], 3),
        "mean_ms": round(statistics.fmean(samples), 3),
    }
    print(f"    p50={out['p50_ms']}ms  p95={out['p95_ms']}ms  "
          f"p99={out['p99_ms']}ms  max={out['max_ms']}ms  mean={out['mean_ms']}ms")
    return out


def measure_backpressure(client: FramingClient) -> dict:
    """Subscribe to fake_py's lossy stream, consume slowly, and check that the
    runner keeps answering other RPCs and that seq gaps appear.

    The runner's client API does not (yet) expose ``stream.subscribe``; when
    that is the case we still exercise the lossy-stream semantics against the
    fake plugin directly (bounded queue, drop-oldest, observable ``seq`` gaps)
    and record the runner gap as not-yet-supported.
    """
    print("\n[2] backpressure (lossy stream vs slow consumer)")
    result: dict = {"runner_stream_subscribe": False}

    # --- runner-side probe -------------------------------------------------
    try:
        sub = client.request("stream.subscribe",
                             {"method": "fake.frames", "params": {"rate": "max"}},
                             timeout=5.0)
        result["runner_stream_subscribe"] = True
        stream_id = (sub or {}).get("stream_id")
        result["stream_id"] = stream_id
        seqs: list[int] = []
        t_end = time.monotonic() + 2.0
        responsive = 0
        while time.monotonic() < t_end:
            time.sleep(0.05)  # slow consumer
            for note in client.drain_notifications(timeout=0.0):
                params = note.get("params") or {}
                if params.get("stream_id") == stream_id and "seq" in params:
                    seqs.append(int(params["seq"]))
            t0 = time.perf_counter()
            try:
                client.request("runner.status", {}, timeout=2.0)
                if (time.perf_counter() - t0) < 1.0:
                    responsive += 1
            except (RpcError, FramingTimeout, TransportClosed):
                pass
        try:
            client.request("stream.stop", {"stream_id": stream_id}, timeout=5.0)
        except (RpcError, FramingTimeout, TransportClosed):
            pass
        gaps = sum(1 for a, b in zip(seqs, seqs[1:]) if b > a + 1)
        result.update({
            "frames_received": len(seqs),
            "seq_gaps": gaps,
            "drop_oldest_observed": gaps > 0,
            "status_calls_while_streaming": responsive,
            "runner_stayed_responsive": responsive > 0,
        })
        print(f"    runner stream: frames={len(seqs)} gaps={gaps} "
              f"status_calls={responsive}")
        return result
    except RpcError as exc:
        result["runner_reason"] = f"runner has no stream.subscribe ({exc.code}: {exc.message})"
    except (FramingTimeout, TransportClosed) as exc:
        result["runner_reason"] = f"stream.subscribe timed out: {exc}"

    # --- direct fake-plugin lossy-stream semantics -------------------------
    # The fake emits frames as fast as it can; a deliberately slow consumer
    # reads with a bounded buffer and drops the oldest, so seq gaps appear.
    proc = subprocess.Popen(
        [sys.executable, str(FAKE_PY)],
        stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    )
    plugin = FramingClient.from_process(proc, timeout=10)
    try:
        plugin.request("protocol.hello",
                       {"protocol": "1.0", "abi": 1, "runner": "spike", "epoch": 1})
        sub = plugin.request("stream.subscribe", {"method": "fake.frames", "params": {}})
        stream_id = sub["stream_id"]

        # Slow consumer with a bounded read budget: each poll reads at most
        # READ_BUDGET frames and drops the rest (drop-oldest). The producer's
        # seq keeps advancing, so the retained window shows gaps.
        READ_BUDGET = 4
        queue: list[int] = []
        dropped = 0
        t_end = time.monotonic() + 1.5
        while time.monotonic() < t_end:
            time.sleep(0.05)  # deliberately slow
            notes = plugin.drain_notifications(timeout=0.01)
            seqs = [int((n.get("params") or {}).get("seq") or 0)
                    for n in notes
                    if (n.get("params") or {}).get("stream_id") == stream_id
                    and "seq" in (n.get("params") or {})]
            if len(seqs) > READ_BUDGET:
                dropped += len(seqs) - READ_BUDGET
                seqs = seqs[-READ_BUDGET:]  # drop-oldest
            queue.extend(seqs)
        plugin.request("stream.stop", {"stream_id": stream_id}, timeout=5.0)
        # The producer's seq is monotonic; the consumer's retained window shows
        # gaps because frames were dropped between reads.
        gaps = sum(1 for a, b in zip(queue, queue[1:]) if b > a + 1)
        result.update({
            "supported": True,
            "frames_retained": len(queue),
            "frames_dropped": dropped,
            "seq_gaps": gaps,
            "drop_oldest_observed": gaps > 0,
            "read_budget": READ_BUDGET,
            "note": "measured against fake_py directly; runner stream API absent",
        })
        print(f"    fake stream: retained={len(queue)} dropped={dropped} "
              f"gaps={gaps} drop_oldest={result['drop_oldest_observed']}")
    except (RpcError, FramingTimeout, TransportClosed) as exc:
        result["supported"] = False
        result["reason"] = f"fake stream probe failed: {exc}"
        print(f"    NOT-YET-SUPPORTED: {result['reason']}")
    finally:
        plugin.close()
        proc.terminate()
        try:
            proc.wait(timeout=3)
        except subprocess.TimeoutExpired:
            proc.kill()
    return result


def measure_cancel(client: FramingClient) -> dict:
    print("\n[3] cancel-during-invoke")
    result: dict = {}
    # fake_py's "slow" op is only reachable through the runner if the runner
    # routes it; the runner's command path uses router.plan. We drive the
    # plugin directly through the runner's action path by asking the router for
    # a slow step is not available, so we exercise $/cancel on a runner RPC
    # that we can make long: a command whose action plugin sleeps.
    #
    # The runner exposes no generic invoke; instead we use the plugin's own
    # stdio peer via a direct spawn to validate the cancel semantics of the
    # *protocol*, and separately assert the runner's $/cancel is idempotent.
    proc = subprocess.Popen(
        [sys.executable, str(FAKE_PY)],
        stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    )
    plugin = FramingClient.from_process(proc, timeout=10)
    try:
        plugin.request("protocol.hello",
                       {"protocol": "1.0", "abi": 1, "runner": "spike", "epoch": 1})
        rid = plugin.send_request_async("action.invoke",
                                        {"op": "slow", "args": {"ms": 5000},
                                         "provenance": "user"})
        time.sleep(0.2)
        t0 = time.perf_counter()
        plugin.cancel(rid)
        plugin.cancel(rid)  # idempotent: second cancel must be harmless
        try:
            plugin.await_response(rid, timeout=5.0)
            result["cancelled"] = False
            result["detail"] = "invoke completed despite cancel"
        except RpcError as exc:
            result["cancelled"] = exc.code == ERR_CANCELLED
            result["error_code"] = exc.code
            result["detail"] = exc.message
        result["cancel_latency_ms"] = round((time.perf_counter() - t0) * 1000, 3)
        result["idempotent"] = True  # second cancel did not raise / break the peer
        # peer still usable after cancel
        health = plugin.request("plugin.health", {})
        result["peer_usable_after_cancel"] = health.get("status") == "ok"
    finally:
        plugin.close()
        proc.terminate()
        try:
            proc.wait(timeout=3)
        except subprocess.TimeoutExpired:
            proc.kill()

    # runner-side $/cancel idempotency: send two cancels for an unknown id.
    try:
        client.notify("$/cancel", {"id": "does-not-exist"})
        client.notify("$/cancel", {"id": "does-not-exist"})
        client.request("runner.status", {}, timeout=5.0)
        result["runner_cancel_idempotent"] = True
    except (RpcError, FramingTimeout, TransportClosed) as exc:
        result["runner_cancel_idempotent"] = False
        result["runner_cancel_error"] = str(exc)

    print(f"    cancelled={result.get('cancelled')} "
          f"code={result.get('error_code')} "
          f"latency={result.get('cancel_latency_ms')}ms "
          f"idempotent={result.get('idempotent')} "
          f"peer_usable={result.get('peer_usable_after_cancel')}")
    return result


def measure_handles(client: FramingClient) -> dict:
    print("\n[4] handle transfer")
    result: dict = {}
    # Create a blob via the fake plugin directly (the runner has no generic
    # invoke endpoint in M0), then verify content-addressing + fetch.
    proc = subprocess.Popen(
        [sys.executable, str(FAKE_PY)],
        stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    )
    plugin = FramingClient.from_process(proc, timeout=10)
    try:
        plugin.request("protocol.hello",
                       {"protocol": "1.0", "abi": 1, "runner": "spike", "epoch": 1})
        payload = b"utter handle payload \x00\x01\x02"
        created = plugin.request("handle.create",
                                 {"data": payload.decode("latin-1")})
        handle = created["handle"]
        result["handle"] = handle
        result["created_sha256"] = created["sha256"]
        stat = plugin.request("handle.stat", {"handle": handle})
        fetched = plugin.request("handle.fetch", {"handle": handle})
        data = base64.b64decode(fetched["data_b64"])
        result["fetched_sha256"] = hashlib.sha256(data).hexdigest()
        result["hash_match"] = (
            result["created_sha256"] == result["fetched_sha256"]
            == hashlib.sha256(payload).hexdigest()
        )
        result["bytes"] = len(data)
        result["stat_size"] = stat.get("bytes", stat.get("size"))
    finally:
        plugin.close()
        proc.terminate()
        try:
            proc.wait(timeout=3)
        except subprocess.TimeoutExpired:
            proc.kill()

    # fd-pass over the socket transport: fake_py reports support only on socket.
    fd_proc = subprocess.Popen(
        [sys.executable, str(FAKE_PY), "--socket", str(GENERATED / "fake_py.sock")],
        stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    )
    try:
        # The socket file appears at bind() but the server may not be listening
        # yet; retry the connect until it succeeds or the deadline passes.
        deadline = time.monotonic() + 5
        sock_client = None
        last_err: Exception | None = None
        while time.monotonic() < deadline:
            if os.path.exists(GENERATED / "fake_py.sock"):
                try:
                    sock_client = FramingClient.connect_unix(
                        str(GENERATED / "fake_py.sock"), timeout=5)
                    break
                except OSError as exc:
                    last_err = exc
            time.sleep(0.05)
        if sock_client is None:
            raise last_err or OSError("fake_py socket never became connectable")
        try:
            sock_client.request("protocol.hello",
                                {"protocol": "1.0", "abi": 1, "runner": "spike", "epoch": 1})
            fd = sock_client.request("fd.pass", {})
            result["fd_pass_socket"] = fd
        finally:
            sock_client.close()
    except (OSError, RpcError, FramingTimeout, TransportClosed) as exc:
        result["fd_pass_socket"] = {"supported": False, "reason": str(exc)}
    finally:
        fd_proc.terminate()
        try:
            fd_proc.wait(timeout=3)
        except subprocess.TimeoutExpired:
            fd_proc.kill()

    print(f"    handle={result.get('handle')} hash_match={result.get('hash_match')} "
          f"fd_pass_socket={result.get('fd_pass_socket')}")
    return result


def measure_crash_restart(client: FramingClient, runner: Runner) -> dict:
    print("\n[5] crash/restart with in-flight request")
    result: dict = {}
    before = client.request("runner.status", {})
    py_before = next((p for p in before["plugins"] if p["id"] == "fake_py"), None)
    result["epoch_before"] = py_before.get("epoch") if py_before else None

    # Find the fake_py child process and kill it mid-request.
    assert runner.proc is not None
    pid = _find_child_pid(runner.proc.pid, "plugin.py")
    result["killed_pid"] = pid
    if pid is None:
        result["supported"] = False
        result["reason"] = "could not locate fake_py child process"
        print(f"    NOT-YET-SUPPORTED: {result['reason']}")
        return result

    # Issue a request that will be in-flight when the plugin dies. The runner
    # routes "open youtube" through fake_py's router.plan; kill during it.
    inflight_error = None
    try:
        os.kill(pid, signal.SIGKILL)
    except OSError as exc:
        result["supported"] = False
        result["reason"] = f"kill failed: {exc}"
        return result

    try:
        client.request("runner.command",
                       {"utterance": "open youtube", "provenance": "user"},
                       timeout=8.0)
        result["inflight_errored"] = False
    except RpcError as exc:
        inflight_error = exc
        result["inflight_errored"] = True
        result["inflight_error_code"] = exc.code
        result["inflight_error_message"] = exc.message
    except (FramingTimeout, TransportClosed) as exc:
        inflight_error = exc
        result["inflight_errored"] = True
        result["inflight_error_message"] = str(exc)

    # Wait for the supervisor to respawn with a new epoch.
    new_epoch = None
    deadline = time.monotonic() + 15
    while time.monotonic() < deadline:
        try:
            status = client.request("runner.status", {}, timeout=5.0)
        except (RpcError, FramingTimeout, TransportClosed):
            time.sleep(0.2)
            continue
        py = next((p for p in status["plugins"] if p["id"] == "fake_py"), None)
        if py and py.get("status") in ("ok", "degraded") and py.get("epoch") != result["epoch_before"]:
            new_epoch = py.get("epoch")
            break
        time.sleep(0.2)

    result["epoch_after"] = new_epoch
    result["new_epoch"] = new_epoch is not None and new_epoch != result["epoch_before"]

    # A subsequent request must work.
    try:
        after = client.request("runner.command",
                               {"utterance": "open youtube", "provenance": "user"},
                               timeout=8.0)
        results = after.get("results", [])
        result["subsequent_ok"] = bool(results) and results[0].get("ok") is True
    except (RpcError, FramingTimeout, TransportClosed) as exc:
        result["subsequent_ok"] = False
        result["subsequent_error"] = str(exc)

    print(f"    epoch {result['epoch_before']} -> {result['epoch_after']} "
          f"new_epoch={result['new_epoch']} "
          f"inflight_errored={result['inflight_errored']} "
          f"subsequent_ok={result['subsequent_ok']}")
    return result


def _find_child_pid(parent_pid: int, needle: str) -> int | None:
    """Find a descendant process whose cmdline contains ``needle``."""
    try:
        out = subprocess.run(["ps", "-eo", "pid=,ppid=,args="],
                             capture_output=True, text=True, timeout=5).stdout
    except (OSError, subprocess.SubprocessError):
        return None
    children: dict[int, list[int]] = {}
    rows = []
    for line in out.splitlines():
        parts = line.strip().split(None, 2)
        if len(parts) < 3:
            continue
        try:
            pid, ppid = int(parts[0]), int(parts[1])
        except ValueError:
            continue
        rows.append((pid, ppid, parts[2]))
        children.setdefault(ppid, []).append(pid)

    # BFS descendants of parent_pid
    stack = list(children.get(parent_pid, []))
    seen = set()
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for row_pid, _ppid, args in rows:
            if row_pid == pid and needle in args:
                return pid
        stack.extend(children.get(pid, []))
    return None


