#!/usr/bin/env python3
"""M0 measurement spike for the utter plugin protocol.

Measures the things that decide whether the protocol is viable:

  1. RPC round-trip latency   — N=200 ``runner.status`` calls -> p50/p95/max
  2. backpressure             — a lossy stream from fake_py emits faster than a
                                deliberately slow consumer; assert the runner
                                stays responsive to other RPCs and that ``seq``
                                gaps are observable (drop-oldest)
  3. cancel-during-invoke     — a long ``action.invoke`` then ``$/cancel``;
                                assert idempotent cancel + cancelled report
  4. handle transfer          — create a blob via the fake, receive a
                                ``handle://`` and ``handle.fetch`` it; verify the
                                content hash matches. fd-pass over the socket
                                transport is exercised if supported, else
                                reported as not-yet-supported.
  5. crash/restart in-flight  — kill the fake plugin mid-request; assert the
                                runner respawns it with a NEW epoch, the
                                in-flight request errors cleanly, and a
                                subsequent request works.

Results are written to ``tests/conformance/report.json`` (machine-readable) and
printed as a human summary.

Usage::

    .venv-agent/bin/python scripts/m0_spike.py [--n 200] [--keep]
"""
