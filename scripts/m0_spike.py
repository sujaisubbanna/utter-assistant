def measure_backpressure_e2e(client: FramingClient) -> dict:
    """End-to-end lossy backpressure through the runner."""
    print("\n[M1.1 end-to-end backpressure through the runner]")
    result: dict = {"supported": False}
    try:
        sub = client.subscribe("fake.frames", {"rate": "max"}, mode="lossy", timeout=5.0)
    except RpcError as exc:
        result["reason"] = f"runner has no stream.subscribe ({exc.code}: {exc.message})"
        print(f"    NOT-YET-SUPPORTED: {result['reason']}")
        return result
    except (FramingTimeout, TransportClosed) as exc:
        result["reason"] = f"stream.subscribe timed out: {exc}"
        print(f"    NOT-YET-SUPPORTED: {result['reason']}")
        return result

    stream_id = str(sub.get("stream_id") or "")
    result["supported"] = True
    result["stream_id"] = stream_id
    result["mode"] = sub.get("mode")

    seqs: list[int] = []
    responsive = 0
    t_end = time.monotonic() + 1.5
    while time.monotonic() < t_end:
        time.sleep(0.05)  # slow consumer
        notes = client.drain_notifications(timeout=0.01)
        batch = [int((n.get("params") or {}).get("seq") or 0)
                 for n in notes
                 if (n.get("params") or {}).get("stream_id") == stream_id
                 and "seq" in (n.get("params") or {})]
        if len(batch) > 4:
            batch = batch[-4:]  # drop-oldest
        seqs.extend(batch)
        t0 = time.perf_counter()
        try:
            client.request("runner.status", {}, timeout=2.0)
            if (time.perf_counter() - t0) < 1.0:
                responsive += 1
        except (RpcError, FramingTimeout, TransportClosed):
            pass

    gaps = sum(1 for a, b in zip(seqs, seqs[1:]) if b > a + 1)
    # stream.stop idempotent
    stop_ok = True
    try:
        client.stop_stream(stream_id, timeout=5.0)
        client.stop_stream(stream_id, timeout=5.0)
    except (RpcError, FramingTimeout, TransportClosed):
        stop_ok = False
    result.update({
        "frames_received": len(seqs),
        "seq_gaps": gaps,
        "drop_oldest_observed": gaps > 0,
        "status_calls_while_streaming": responsive,
        "runner_stayed_responsive": responsive > 0,
        "stream_stop_idempotent": stop_ok,
    })
    print(f"    frames={len(seqs)} gaps={gaps} status_calls={responsive} "
          f"stop_idempotent={stop_ok}")
    return result


def measure_reliable_flow(client: FramingClient) -> dict:
    """Reliable flow control: pause on credit exhaustion, resume on ack."""
    print("\n[M1.2 reliable flow control]")
    result: dict = {"supported": False}
    try:
        sub = client.subscribe("fake.frames", {}, mode="reliable", timeout=5.0)
    except RpcError as exc:
        result["reason"] = f"runner has no stream.subscribe ({exc.code}: {exc.message})"
        print(f"    NOT-YET-SUPPORTED: {result['reason']}")
        return result
    except (FramingTimeout, TransportClosed) as exc:
        result["reason"] = f"stream.subscribe timed out: {exc}"
        print(f"    NOT-YET-SUPPORTED: {result['reason']}")
        return result

    stream_id = str(sub.get("stream_id") or "")
    result["supported"] = True
    result["stream_id"] = stream_id
    result["mode"] = sub.get("mode")

    first = client.collect_stream(stream_id, duration=0.6)
    first_seqs = [int((n.get("params") or {}).get("seq") or 0) for n in first]
    max_before = max(first_seqs) if first_seqs else 0
    time.sleep(0.4)
    paused = client.collect_stream(stream_id, duration=0.3)
    paused_seqs = [int((n.get("params") or {}).get("seq") or 0) for n in paused]
    max_paused = max(paused_seqs) if paused_seqs else max_before
    result["max_seq_before_pause"] = max_before
    result["max_seq_after_pause"] = max_paused
    result["paused"] = max_paused <= max_before + 2

    ack_ok = True
    try:
        client.ack(stream_id, max_paused, timeout=5.0)
    except (RpcError, FramingTimeout, TransportClosed):
        ack_ok = False
    resumed = client.collect_stream(stream_id, duration=0.5)
    resumed_seqs = [int((n.get("params") or {}).get("seq") or 0) for n in resumed]
    max_resumed = max(resumed_seqs) if resumed_seqs else max_paused
    result["ack_ok"] = ack_ok
    result["max_seq_after_ack"] = max_resumed
    result["resumed"] = max_resumed > max_paused
    client.stop_stream(stream_id)
    print(f"    max_before={max_before} max_paused={max_paused} "
          f"max_resumed={max_resumed} paused={result['paused']} "
          f"resumed={result['resumed']}")
    return result


def measure_invoke(client: FramingClient) -> dict:
    """runner.invoke: cross-language action + router.plan + provenance."""
    print("\n[M1.3 runner.invoke]")
    result: dict = {"supported": False}
    try:
        rs = client.invoke("fake_rs", "action.invoke",
                           {"op": "ensure_url",
                            "args": {"url": "https://www.youtube.com"},
                            "provenance": "user"}, timeout=10.0)
        result["supported"] = True
        result["fake_rs_ok"] = isinstance(rs, dict) and rs.get("ok") is True
        result["fake_rs_result"] = rs
    except RpcError as exc:
        result["reason"] = f"runner has no runner.invoke ({exc.code}: {exc.message})"
        print(f"    NOT-YET-SUPPORTED: {result['reason']}")
        return result
